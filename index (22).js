// Background Attack Function
async function runAttack(senderJid, targetJid, type, customMsg = null) {
    activeAttacks.set(senderJid, true);
    let count = 0;
    
    // الهجوم يرسل المصفوفة بالكامل بالتسلسل كما في الكود الأصلي
    if (type === 'spam') {
        for (const insult of insults) {
            if (!activeAttacks.get(senderJid)) break;
            try {
                await sock.sendMessage(targetJid, { text: insult });
                count++;
                dailyMessageCount++;
                await delay(250); // سرعة القصف
            } catch (e) { break; }
        }
    } else {
        while (activeAttacks.get(senderJid)) {
            try {
                await sock.sendMessage(targetJid, { text: customMsg });
                count++;
                dailyMessageCount++;
                await delay(250);
            } catch (e) { break; }
        }
    }
    await sock.sendMessage(senderJid, { text: `✅ انتهى القصف. تم إرسال ${count} رسالة.` });
    activeAttacks.delete(senderJid);
}

async function startBot() {
    console.log('💀 بوت [ المُتحكِّم ] قيد التشغيل...');
    const { state, saveCreds } = await useMultiFileAuthState(AUTH_DIR);
    const { version } = await fetchLatestBaileysVersion();

    sock = makeWASocket({
        version,
        auth: state,
        logger: pino({ level: 'silent' }),
        printQRInTerminal: true,
        browser: Browsers.macOS("Desktop"),
        qrTimeout: 0,
        connectTimeoutMs: 60000
    });

    sock.ev.on('creds.update', saveCreds);

    sock.ev.on('connection.update', async (update) => {
        const { connection, lastDisconnect, qr } = update;
        if (qr) {
            console.log('📸 امسح الرمز للربط:');
            qrcode.generate(qr, { small: false });
        }
        if (connection === 'close') {
            const shouldReconnect = (lastDisconnect.error instanceof Boom) ? 
                lastDisconnect.error.output.statusCode !== DisconnectReason.loggedOut : true;
            if (shouldReconnect) startBot();
        } else if (connection === 'open') {
            console.log('✅ تم الاتصال بنجاح!');
            await sock.sendMessage(ADMIN_JID, { text: 'تعالا نيك حد' });
        }
    });

    sock.ev.on('messages.upsert', async (m) => {
        if (m.type !== 'notify') return;
        const msg = m.messages[0];
        if (!msg.message || msg.key.fromMe) return;

        const jid = msg.key.remoteJid;
        const text = (msg.message.conversation || msg.message.extendedTextMessage?.text || '').trim();
        console.log(`📩 [${jid}]: ${text}`);
        
        let state = userState.get(jid);

        // Session reset after 2 hours
        if (state?.lastSeen && (Date.now() - state.lastSeen > 2 * 60 * 60 * 1000)) {
            userState.delete(jid);
            authenticatedUsers.delete(jid);
            await sock.sendMessage(jid, { text: 'ده انا الي نكتلك الي فشخوك شتيمه ، تعالا اشكرني' });
            return;
        }
        userState.set(jid, { ...state, lastSeen: Date.now() });
        state = userState.get(jid);

        // Authentication
        if (!authenticatedUsers.has(jid)) {
            if (text === PASSWORD) {
                authenticatedUsers.add(jid);
                passwordAttempts.delete(jid);
                await sock.sendMessage(jid, { text: '╭─「 *مـرحـبـاً بـك فـي عـالـمـي الـمـظـلـم* 」\n│\n│ *أهـلاً بـك أيـهـا الـمـسـتـخـدم الـجـديـد،*\n│ *لـقـد تـم تـسـجـيـل دخـولـك بـنـجـاح.*\n│ *أرسـل "اوامر" لـتـتـلـقـى تـعـلـيـمـاتـي.* \n│\n╰─「 *بـوت الـدمـار الـشـامـل* 」' });
            } else if (text === 'انا آسف لــ عمي سيف') {
                passwordAttempts.delete(jid);
                await sock.sendMessage(jid, { text: 'تم إعادة تعيين محاولات كلمة المرور.' });
            } else if (text !== '') {
                let attempts = (passwordAttempts.get(jid) || 0) + 1;
                passwordAttempts.set(jid, attempts);
                await sock.sendMessage(jid, { text: `كسمك ${attempts === 1 ? 'مره' : attempts === 2 ? 'مرتين' : attempts + ' مرات'}` });
            }
            return;
        }

        // Global Stop Command
        if (text === 'توقف' || text === 'stop') {
            activeAttacks.delete(jid);
            userState.set(jid, { ...state, step: 'menu' });
            await sock.sendMessage(jid, { text: '🛑 تم إيقاف الهجوم.' });
            return;
        }

        // Commands
        if (text === 'اوامر' || text === 'الاوامر' || text === 'menu') {
            userState.set(jid, { ...state, step: 'menu' });
            await sock.sendMessage(jid, { text: '💀 قائمة الفناء 💀\n\n1 - إغراق الأرقام\n2 - هجوم مخصص\n3 - الحالة' });
            return;
        }

        if (state?.step === 'menu') {
            if (text === '1') {
                userState.set(jid, { ...state, step: 'target_spam' });
                await sock.sendMessage(jid, { text: '😈 أدخل رقم الضحية:' });
                return;
            } else if (text === '2') {
                userState.set(jid, { ...state, step: 'target_custom' });
                await sock.sendMessage(jid, { text: '💀 أدخل الرقم المستهدف للهجوم المخصص:' });
                return;
            } else if (text === '3') {
                await sock.sendMessage(jid, { text: `🤖 نظام macOS نشط.\nالرسائل اليوم: ${dailyMessageCount}` });
                return;
            }
        }

        if (state?.step === 'target_spam') {
            let phone = text.replace(/[^\d]/g, '');
            if (phone.startsWith('01') && phone.length === 11) phone = '20' + phone;
            const target = phone + '@s.whatsapp.net';
            await sock.sendMessage(jid, { text: '🚀 جاري القصف...' });
            runAttack(jid, target, 'spam');
            userState.set(jid, { ...state, step: 'active' });
            return;
        }

        if (state?.step === 'target_custom') {
            let phone = text.replace(/[^\d]/g, '');
            if (phone.startsWith('01') && phone.length === 11) phone = '20' + phone;
            userState.set(jid, { ...state, step: 'custom_msg', targetPhone: phone });
            await sock.sendMessage(jid, { text: 'أدخل نص الرسالة المستمرة:' });
            return;
        }

        if (state?.step === 'custom_msg') {
            const target = state.targetPhone + '@s.whatsapp.net';
            await sock.sendMessage(jid, { text: '🚀 بدأ الهجوم المخصص...' });
            runAttack(jid, target, 'custom', text);
            userState.set(jid, { ...state, step: 'active' });
            return;
        }

        // الرد على أي رسالة غير مفهومة
        if (text !== '') {
            await sock.sendMessage(jid, { text: 'ولااااا ي غبااااااوه روح اتعلم ازاي اشغل البوت 🫩' });
        }
    });
}

